  /**
   * إحداثيات العرض للمدينة أو الحي
   * @returns {{ lat: number, lng: number, zoom: number } | null}
   */
  getViewForLocation(city, district) {
    if (!city) return null;
    const cities = this.cityCenters || {};
    const districts = this.districtCenters || {};
    const cityBase = cities[city];

    if (district) {
      const exact = districts[city]?.[district];
      if (exact) {
        return { lat: exact[0], lng: exact[1], zoom: exact[2] ?? 14 };
      }
      if (cityBase) {
        return this._approximateDistrict(city, district, cityBase);
      }
      return null;
    }

    if (cityBase) {
      return { lat: cityBase[0], lng: cityBase[1], zoom: cityBase[2] ?? 11 };
    }
    return null;
  },

  _approximateDistrict(city, district, cityBase) {
    let h = 0;
    const s = `${city}\0${district}`;
    for (let i = 0; i < s.length; i += 1) {
      h = (Math.imul(31, h) + s.charCodeAt(i)) | 0;
    }
    const angle = ((h >>> 0) % 360) * (Math.PI / 180);
    const dist = 0.012 + ((h >>> 0) % 80) / 6000;
    const lngScale = cityBase[0] < 25 ? 1.12 : 1;
    return {
      lat: cityBase[0] + dist * Math.sin(angle),
      lng: cityBase[1] + dist * Math.cos(angle) * lngScale,
      zoom: 14,
    };
  },
